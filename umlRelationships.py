class Hearts:
    def __init__(self, amount):
        self.amount = amount
        print(f"Healthbar has {self.amount} hearts")

    def lose_heart(self, amount):
        self.amount = max(0, self.amount - amount)
        print(f"Healthbar: {self.amount} hearts")


class Player:
    def __init__(self, username):
        self.username = username
        self.alive = True
        self.hearts = Hearts(20)

        print(f"{self.username} has joined UNSTABLE SMP")

    def take_damage(self, amount):
        if not self.alive:
            print(f"{self.username} is dead.")
            return

        print(f"{self.username} takes {amount} damage")
        self.hearts.lose_heart(amount)

        if self.hearts.amount == 0:
            self.die()

    def die(self):
        if self.alive:
            self.alive = False
            print(f"{self.username} was smashed by Nitenly")

            del self.hearts
            print("Hearts: 0")


player1 = Player("Jaden_man")

player1.take_damage(5)
player1.take_damage(15)

